"""Inventory optional cache cleanup; never delete or alter retained artifacts."""
from datetime import datetime, timezone
from pathlib import Path
import json
import os
import subprocess

ROOT = Path(__file__).resolve().parents[3]
RECORD = Path(__file__).resolve().parent
skip = {'.git', '.venv', '.venv-implementation', 'node_modules', '_build', 'test-execution', '_security-audits'}
candidates = []
for parent, directories, files in os.walk(ROOT):
    directories[:] = [d for d in directories if d not in skip]
    for name in list(directories):
        if name in {'__pycache__', '.pytest_cache'}:
            path = Path(parent)/name
            candidates.append(dict(path=path.relative_to(ROOT).as_posix(),
                bytes=sum(p.stat().st_size for p in path.rglob('*') if p.is_file()),
                reason='Reproducible Python/pytest cache; regenerated by later tooling/tests.'))
            directories.remove(name)
status = subprocess.check_output(['git','status','--short','--ignored'],cwd=ROOT,text=True)
(RECORD/'workspace-status.txt').write_text(status,encoding='utf-8')
total = sum(i['bytes'] for i in candidates)
(RECORD/'cleanup-inventory.json').write_text(json.dumps(dict(
    timestamp=datetime.now(timezone.utc).isoformat(), candidates=candidates, total_bytes=total,
    retained=['Entire dist/ including older distributions', 'All release evidence and exact tested artifacts',
              'Active environments, offline wheelhouse and frontend dependencies',
              'Current documentation build, retained old/failed builds and current capacity fixture'],
    uncertain='Older ignored build/diagnostic trees remain retained; no automatic deletion is authorized.',
    deletion='None; explicit approval of listed paths would be required.'),indent=2),encoding='utf-8')
lines = ['Workspace cleanup review','='*28,'',
         'Tracked, untracked and ignored status and the filesystem cache inventory were',
         'reviewed after qualification. No files were deleted. These optional cache',
         'paths may be removed only after explicit owner approval; approval is not',
         'needed to retain them. Later Python/pytest runs regenerate them.','',
         '.. list-table:: Optional cache cleanup','   :header-rows: 1','',
         '   * - Project-relative directory','     - Bytes','     - Reason']
for item in candidates:
    lines += ['   * - ``'+item['path']+'``','     - '+str(item['bytes']),'     - '+item['reason']]
lines += ['', f'Total optional reclaimable space: {total:,} logical bytes.', '',
          'The entire dist directory, all historical/current distributions and release',
          'evidence, active environments, dependency installations, offline wheelhouse,',
          'current documentation, old/failed publication trees and capacity fixture',
          'are retained. Older ignored diagnostics remain uncertain and are not proposed',
          'for deletion. The current benchmark is useful reproducible qualification input.', '',
          'A post-release status/filesystem check remains due after hosted publication.', '',
          '* :download:`Exact inventory <cleanup-inventory.json>`',
          '* :download:`Tracked/untracked/ignored status <workspace-status.txt>`']
(RECORD/'cleanup-review.rst').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'{len(candidates)} optional cache directories, {total:,} bytes; nothing deleted.')
